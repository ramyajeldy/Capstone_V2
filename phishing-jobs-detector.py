def predict_job_text(text, threshold=THRESHOLD):
    if not text or not text.strip():
        return {
            "label": "unknown",
            "is_fake_job": False,
            "fraud_probability": 0.0,
            "legitimate_probability": 0.0,
            "confidence": 0.0,
            "message": "Empty input text."
        }

    inputs = inference_tokenizer(
        text,
        return_tensors="pt",
        truncation=True,
        padding="max_length",
        max_length=MAX_LENGTH,
    )
    inputs = {k: v.to(device) for k, v in inputs.items()}

    with torch.no_grad():
        outputs = inference_model(**inputs)
        probs = torch.softmax(outputs.logits, dim=-1).cpu().numpy()[0]

    legit_prob = float(probs[0])
    fraud_prob = float(probs[1])
    predicted_label = 1 if fraud_prob >= threshold else 0

    return {
        "label": "fake_job" if predicted_label == 1 else "legitimate_job",
        "is_fake_job": predicted_label == 1,
        "fraud_probability": round(fraud_prob, 4),
        "legitimate_probability": round(legit_prob, 4),
        "confidence": round(max(legit_prob, fraud_prob), 4),
        "threshold_used": threshold,
    }

