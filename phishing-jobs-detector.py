def safe_str(value):
    if value is None:
        return ""
    return str(value).strip()

def build_job_text(example):
    fields = [
        safe_str(example.get("title", "")),
        safe_str(example.get("description", "")),
        safe_str(example.get("required_experience", "")),
        safe_str(example.get("required_education", "")),
        safe_str(example.get("salary_range", "")),
        safe_str(example.get("company_profile", "")),
        safe_str(example.get("benefits", "")),
        safe_str(example.get("requirements", "")),
        safe_str(example.get("industry", "")),
        safe_str(example.get("function", "")),
        safe_str(example.get("location", "")),
    ]
    text = " ".join([x for x in fields if x])
    return {"text": text}

text_dataset = DatasetDict({
    "train": dataset["train"].map(build_job_text),
    "validation": dataset["validation"].map(build_job_text),
    "test": dataset["test"].map(build_job_text),
})

